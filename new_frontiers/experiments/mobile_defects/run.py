"""Two moving objects whose composition creates a submodular defect.

Run: python3 -m new_frontiers.experiments.mobile_defects.run --output-dir /tmp/mobile-defects
Standard library only. Evolution uses Gaussian integer numerators and an exact
common denominator. No source is fixed, and there are no spatial boundaries.

Added laws: two-direction quantum travel with the previous balanced mixer;
contact phase (-1)**defect. These laws do not follow from the poset alone.
"""

from collections import defaultdict
from fractions import Fraction as F
from pathlib import Path
import argparse
import json

from .._shared.exact import QComplex, ONE, ZERO, times, plus, conjugate
from .._shared.k4_graph import EDGES, defect, mass


def mask(edges):
    return sum(1 << EDGES.index(edge) for edge in edges)


LEFT = mask(((0, 1), (1, 2)))
CLOSING = mask(((0, 2),))
OPEN = mask(((2, 3),))
VELOCITIES = ((1, 1), (1, -1), (-1, 1), (-1, -1))
R, I, NI = (1, 0), (0, 1), (0, -1)
# (B tensor B) = COIN / 2, in the order RR, RL, LR, LL.
COIN = ((I, R, R, NI), (R, I, NI, R), (R, NI, I, R), (NI, R, R, I))


def located_mass(x, y, right):
    """Compute nullity on the actual graph with vertices (site, local_vertex)."""
    edges = set()
    for location, subset in ((x, LEFT), (y, right)):
        edges.update(((location, a), (location, b)) for i, (a, b) in enumerate(EDGES)
                     if subset & (1 << i))
    vertices = {v for edge in edges for v in edge}
    parent = {v: v for v in vertices}

    def root(v):
        while parent[v] != v:
            v = parent[v]
        return v

    rank = 0
    for a, b in edges:
        a, b = root(a), root(b)
        if a != b:
            parent[a] = b
            rank += 1
    return len(edges) - rank


def sign(x, y, right):
    # For these individually massless, disjoint components, the pair defect
    # equals total nullity, and is zero unless the components share a site.
    return -1 if x == y and defect(LEFT, right) % 2 else 1


def evolve(state, right, inverse=False):
    """One unitary step; the common amplitude denominator grows by a factor 2."""
    result = {}
    for (x, y, direction), value in state.items():
        if inverse:
            dx, dy = VELOCITIES[direction]
            x, y = x - dx, y - dy
        value = tuple(sign(x, y, right) * z for z in value)
        for output in range(4):
            coefficient = conjugate(COIN[direction][output]) if inverse else COIN[output][direction]
            dx, dy = (0, 0) if inverse else VELOCITIES[output]
            key = x + dx, y + dy, output
            result[key] = plus(result.get(key, (0, 0)), times(coefficient, value))
    return {key: value for key, value in result.items() if value != (0, 0)}


def initial_state(separation):
    # An explicitly chosen normalized coin state (RL - LR)/sqrt(2).
    # Its initial coin entanglement is supplied, not generated by this run.
    return {(-separation, separation, 1): (1, 0),
            (-separation, separation, 2): (-1, 0)}


def snapshot(state, step, right):
    denominator = 2 * 4**step
    relative, center = defaultdict(int), defaultdict(int)
    contact = close = distance = center_square = 0
    for (x, y, _), (real, imag) in state.items():
        weight = real * real + imag * imag
        assert (x - y) % 2 == 0 and (x + y) % 2 == 0
        relative[(x - y) // 2] += weight
        center[(x + y) // 2] += weight
        contact += weight if x == y else 0
        close += weight if abs(x - y) <= 4 else 0
        distance += abs(x - y) * weight
        center_square += ((x + y) // 2)**2 * weight
    assert sum(relative.values()) == sum(center.values()) == denominator

    def distribution(weights):
        return [{"x": x, "p": float(F(n, denominator)), "exact": str(F(n, denominator))}
                for x, n in sorted(weights.items())]

    return {"step": step, "norm": "1", "contact": str(F(contact, denominator)),
            "expected_defect": str(F(contact * defect(LEFT, right), denominator)),
            "close": str(F(close, denominator)), "mean_separation": str(F(distance, denominator)),
            "center_second_moment": str(F(center_square, denominator)),
            "relative": distribution(relative), "center": distribution(center)}


def exact_structure_checks():
    assert mass(LEFT) == mass(CLOSING) == mass(OPEN) == 0
    assert defect(LEFT, CLOSING) == mass(LEFT | CLOSING) == 1
    assert defect(LEFT, OPEN) == mass(LEFT | OPEN) == 0
    for x in range(-2, 3):
        for y in range(-2, 3):
            for right in (CLOSING, OPEN):
                m = located_mass(x, y, right)
                assert m == (defect(LEFT, right) if x == y else 0)
                assert sign(x, y, right) == (-1)**m
    for a in range(4):
        for b in range(4):
            value = (0, 0)
            for row in COIN:
                value = plus(value, times(conjugate(row[a]), row[b]))
            assert value == ((4, 0) if a == b else (0, 0))

    def exchange(state):
        return {(y, x, (0, 2, 1, 3)[d]): value for (x, y, d), value in state.items()}

    def translate(state):
        return {(x + 3, y + 3, d): value for (x, y, d), value in state.items()}

    state = initial_state(2)
    for _ in range(7):
        assert evolve(exchange(state), CLOSING) == exchange(evolve(state, CLOSING))
        assert evolve(translate(state), CLOSING) == translate(evolve(state, CLOSING))
        state = evolve(state, CLOSING)
    free = interacting = initial_state(4)
    for _ in range(4):
        free, interacting = evolve(free, OPEN), evolve(interacting, CLOSING)
        assert free == interacting


def exact_bound_sector():
    """Check the K=0 relative bound mode in an exact quadratic algebra.

    Represent a+b*lambda, where lambda**2 = 1+(2i/3)*lambda and |lambda|=1.
    The roots are (+/-2sqrt(2)+i)/3. No numerical eigenvalue solver is used.
    The general moving band is derived in new_frontiers/experiments/mobile_defects/README.md.
    """
    tau = QComplex(0, F(2, 3))

    def add(x, y):
        return x[0] + y[0], x[1] + y[1]

    def mul(x, y):
        return (x[0] * y[0] + x[1] * y[1],
                x[0] * y[1] + x[1] * y[0] + tau * x[1] * y[1])

    def scale(a, x):
        return a * x[0], a * x[1]

    def bar(x):
        return x[0].conjugate() - tau * x[1].conjugate(), x[1].conjugate()

    one, zero, lam = (ONE, ZERO), (ZERO, ZERO), (ZERO, ONE)
    assert mul(lam, bar(lam)) == one
    amplitude = scale(QComplex(0, -1), bar(lam))
    rho = F(1, 3)
    stationary = scale(F(1, 2), mul(add(amplitude, (QComplex(-rho), ZERO)), bar(lam)))
    positive = (stationary, amplitude, (QComplex(-rho), ZERO), stationary)
    origin = (zero, one, scale(-1, one), zero)

    def coin(vector):
        return tuple(scale(F(1, 2), sum_vectors([
            scale(QComplex(*COIN[i][j]), vector[j]) for j in range(4)])) for i in range(4))

    def sum_vectors(vectors):
        total = zero
        for vector in vectors:
            total = add(total, vector)
        return total

    at_positive, at_origin = coin(positive), coin(tuple(scale(-1, v) for v in origin))
    assert at_origin[1] == mul(lam, amplitude)
    assert at_origin[2] == scale(-1, mul(lam, amplitude))
    assert at_positive[0] == mul(lam, stationary)
    assert at_positive[3] == mul(lam, stationary)
    assert at_positive[1] == scale(rho, mul(lam, amplitude))
    assert at_positive[2] == scale(-1, lam)
    assert scale(rho, at_positive[2]) == mul(lam, positive[2])
    norm = sum_vectors([mul(v, bar(v)) for v in positive])
    assert norm == (QComplex(F(16, 9)), ZERO)
    assert 2 + 2 * F(16, 9) / (1 - rho**2) == 6
    return {"sector": "total momentum K = 0; antisymmetric exchange sector",
            "eigenvalues": "(+/-2sqrt(2)+i)/3", "relative_tail_ratio": "1/9",
            "normalization_squared": "1/6", "contact_probability": "1/3",
            "general_band": "lambda = +/-sqrt(1-cos(K)^2/9) + i*cos(K)/3",
            "general_decay_amplitude": "rho = cos(K)/3",
            "maximum_band_speed": "1/3",
            "coincident_singlet_projection_on_two_bands": "2/3",
            "general_certificate": "new_frontiers/experiments/mobile_defects/certificate.py plus the domain argument in new_frontiers/experiments/mobile_defects/README.md",
            "qualification": "A single momentum sector is extended in the pair center; localized pairs use band wave packets."}


def run_case(steps, separation, right):
    start = state = initial_state(separation)
    records = [snapshot(state, 0, right)]
    for t in range(1, steps + 1):
        state = evolve(state, right)
        records.append(snapshot(state, t, right))
    for _ in range(steps):
        state = evolve(state, right, inverse=True)
    factor = 2**(2 * steps)
    assert state == {key: tuple(factor * z for z in value) for key, value in start.items()}
    return records



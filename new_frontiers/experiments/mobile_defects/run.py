def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--steps', type=int, default=32)
    parser.add_argument('--output-dir', type=Path)
    parser.add_argument('--with-explorer', action='store_true',
                        help='also generate the optional HTML explorer in --output-dir')
    args = parser.parse_args()
    if args.with_explorer and not args.output_dir:
        parser.error('--with-explorer requires --output-dir')
    if not 4 <= args.steps <= 64:
        parser.error('choose 4–64 steps')
    exact_structure_checks()
    results = {'steps': args.steps, 'bound_band': exact_bound_sector(), 'runs': {}}
    for label, separation in (('together', 0), ('separated', 4)):
        for kind, right in (('closing', CLOSING), ('open', OPEN)):
            name = f'{label}_{kind}'
            records = run_case(args.steps, separation, right)
            results['runs'][name] = records
            last = records[-1]
            print(f"{name}: close={float(F(last['close'])):.6f}, "
                  f"mean separation={float(F(last['mean_separation'])):.6f}, "
                  f"center second moment={float(F(last['center_second_moment'])):.6f}")
    print(json.dumps(results['bound_band'], indent=2))
    print('Exact normalization, reversal, locality, translation, exchange, and K=0 bound-mode checks passed.')
    if args.output_dir:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        (args.output_dir / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
        if args.with_explorer:
            (args.output_dir / 'explorer.html').write_text(explorer(results))


if __name__ == '__main__':
    main()
